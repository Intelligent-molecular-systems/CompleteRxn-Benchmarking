#!/usr/bin/env python3
"""Render the expert-audit reactions (shown as chemistry-annotator audits) and write LaTeX appendix snippets.

Reads only the anonymized tables written by export_cases.py and writes to
results/additional/expert_audits/:

  figures/*.png                  one image per reaction row
  appendix_target_audit.tex      manuscript, target audit (A.2): agreement table
                                 and one figure per agreement level, with every
                                 control that no annotator matches
  appendix_metric_audit.tex      manuscript, metric audit (B.4): table of all 20
                                 cases and one figure per shown annotator judgement
  expert_audits_all_cases.tex    repository: figures of all 20 metric-audit cases

Examples are chosen by fixed rules, stated in the captions:
  target audit   for each number of matching annotators (3, 2 or 1 of 3), the
                 control with the lowest ID; all controls with no match
  metric audit   for each annotator judgement in SHOWN_OUTCOMES, the case with
                 the highest annotator confidence, ties broken by the lowest case number

Include the snippets with \\input. The LaTeX expects the images under
figures_camera_ready/audits/ relative to the main .tex file; choose another
location with --tex-figure-dir, or redefine \\expertauditdir before the \\input.
--copy-figures-to copies the images the manuscript snippets use.

    python analysis/expert_audits/build_appendix.py \\
      --copy-figures-to paper/figures_camera_ready/audits
"""

import argparse
import re
import shutil
from pathlib import Path
import sys

import pandas as pd
from rdkit import RDLogger


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(HERE))
from draw_reaction import differences, draw_reaction  # noqa: E402

OUT = ROOT / "results/additional/expert_audits"
FIGURES = OUT / "figures"
DPI = 300
LABEL_WIDTH = "2.4cm"

OUTCOMES = {
    "equivalent": "equivalent",
    "FlowER": "FlowER target preferred",
    "SynRBL": "SynRBL completion preferred",
    "both": "both plausible",
    "uncertain": "uncertain",
}
# Outcomes with an example figure in the manuscript. Uncertain cases are only tabulated.
SHOWN_OUTCOMES = ["equivalent", "FlowER", "SynRBL", "both"]
CONFIDENCE = {"High": 0, "Medium": 1, "Low": 2}
NUMBERS = {0: "none", 1: "one", 2: "two", 3: "three"}

# All images share one length per pixel, so molecules have the same size everywhere.
PREAMBLE = r"""% Generated by analysis/expert_audits/build_appendix.py; do not edit by hand.
\providecommand{\expertauditdir}{FIGURE_DIR}
\providecommand{\expertauditsection}{\subsection}
\providecommand{\expertauditbarrier}{\clearpage}
\makeatletter\@ifundefined{expertauditpx}{\newlength{\expertauditpx}}{}\makeatother
\setlength{\expertauditpx}{\dimexpr(\textwidth-LABEL-2mm)/WIDEST\relax}
""".replace("LABEL", LABEL_WIDTH)
SHADING = (
    r"Shaded molecules in the target are missing from the same side of at least one "
    r"compared completion. Shaded molecules in a completion do not occur on the same "
    r"side of the target. Agents are drawn above the arrow and are not compared."
)
widths = []


def tex(text):
    for old, new in (("\\", r"\textbackslash{}"), ("_", r"\_"), ("%", r"\%"),
                     ("&", r"\&"), ("#", r"\#")):
        text = text.replace(old, new)
    return text


def render(reaction, name, shade=((), ()), reference=None):
    image = draw_reaction(reaction, shade, reference)
    image.save(FIGURES / name, dpi=(DPI, DPI))
    widths.append(image.width)
    return name, image.width


def float_env(kind, body, caption, label):
    if ";" in caption:
        raise ValueError("Captions must not contain ';': {}".format(label))
    caption = [r"\caption{%s}" % caption, r"\label{%s}" % label]
    # Table captions go above the table, figure captions below the figure.
    body = caption + body if kind == "table" else body + caption
    return "\n".join([r"\begin{%s}[htbp]" % kind, r"\centering\small"] + body + [
        r"\end{%s}" % kind, ""])


def refs(labels):
    labels = list(labels)
    if len(labels) == 1:
        return r"Figure~\ref{%s}" % labels[0]
    return r"Figures~\ref{%s}--\ref{%s}" % (labels[0], labels[-1])


def intro(title, label, text):
    return "\n".join([r"\expertauditsection{%s}" % title, r"\label{%s}" % label, "", text, ""])


def figure(rows, caption, label):
    body = [r"\begin{tabular}{@{}p{%s}@{\hspace{2mm}}l@{}}" % LABEL_WIDTH]
    for i, (row_label, (name, pixels)) in enumerate(rows):
        body.append(r"%s & \raisebox{-.5\height}{\includegraphics[width=%d\expertauditpx]{\expertauditdir/%s}} \\%s" % (
            row_label, pixels, name, r"[2mm]" if i < len(rows) - 1 else ""))
    body.append(r"\end{tabular}")
    return float_env("figure", body, caption, label)


def table(header, rows, columns, caption, label):
    body = [r"\begin{tabular}{%s}" % columns, r"\toprule", header + r" \\", r"\midrule"]
    body += [row + r" \\" for row in rows]
    body += [r"\bottomrule", r"\end{tabular}"]
    return float_env("table", body, caption, label)


# Metric audit (Appendix B.4)

def metric_label(audit_id, prefix="fig:metric_audit_case_"):
    return "{}{}".format(prefix, audit_id)


def metric_case_figure(case, note="", label_prefix="fig:metric_audit_case_"):
    stem = "metric_audit_{:02d}".format(case.audit_id)
    rows = [
        ("USPTO input", render(case.input_reaction, stem + "_input.png")),
        ("FlowER target", render(
            case.flower_target, stem + "_target.png",
            differences(case.flower_target, [case.synrbl_completion], stereo=False))),
        ("SynRBL completion", render(
            case.synrbl_completion, stem + "_synrbl.png",
            differences(case.synrbl_completion, [case.flower_target], stereo=False),
            case.flower_target)),
    ]
    caption = (
        r"Equivalence-metric audit, case {id} ({uid}). Annotator judgement: {outcome} "
        r"(confidence: {conf}). Revised equivalence metric: {metric}. {shading} "
        r"Stereochemistry is ignored, as for all SynRBL comparisons.{note}"
    ).format(
        id=case.audit_id, uid=r"\texttt{%s}" % tex(case.unique_identifier),
        outcome=OUTCOMES[case.expert_outcome], conf=case.expert_confidence.lower(),
        metric="equivalent" if case.equivalent_match else "not equivalent",
        shading=SHADING, note=note,
    )
    return figure(rows, caption, metric_label(case.audit_id, label_prefix))


def metric_appendix(cases, selected, counts):
    rows = []
    for case in cases.itertuples():
        shown = r"\ref{%s}" % metric_label(case.audit_id) if case.audit_id in selected else ""
        rows.append("%d & %s & %s & %s & %s" % (
            case.audit_id, OUTCOMES[case.expert_outcome], case.expert_confidence,
            "equivalent" if case.equivalent_match else "not equivalent", shown))
    caption = (
        r"Chemistry-annotator judgements for all 20 audited SynRBL completions that the initial "
        r"equivalence metric classified as incorrect, the label assigned by the revised "
        r"metric used throughout this paper, and the figures that show examples."
    )
    hidden = [o for o in OUTCOMES if o not in SHOWN_OUTCOMES and counts.get(o)]
    hidden_text = " ".join(
        r"The {n} cases judged {o} appear only in the table.".format(
            n=NUMBERS.get(counts[o], counts[o]), o=OUTCOMES[o]) for o in hidden)
    text = (
        r"This appendix shows reactions from the audit of the equivalence metric by a chemistry annotator "
        r"(Appendix~\ref{{app:equiv_acc_metric}}). Table~\ref{{tab:metric_audit_cases}} lists "
        r"the annotator judgement for all 20 audited SynRBL completions and the label "
        r"assigned by the revised metric. For each judgement{exclusion}, we show the "
        r"case with the highest annotator confidence, with ties broken by the lowest case "
        r"number ({figs}). {hidden} Figures of all 20 cases are provided in the code "
        r"repository. Each figure shows the USPTO input, the FlowER target and the SynRBL "
        r"completion, drawn at the same scale. Shading marks molecules that differ "
        r"between the target and the completion."
    ).format(
        figs=refs(metric_label(i) for i in selected), hidden=hidden_text,
        exclusion=(" except " + " and ".join(OUTCOMES[o] for o in hidden)) if hidden else "",
    ).replace("  ", " ")
    parts = [intro("Reactions from the audit of the equivalence metric",
                   "app:metric_audit_cases", text)]
    parts += [table(r"Case & Annotator judgement & Confidence & Revised metric & Figure", rows,
                   "rllll", caption, "tab:metric_audit_cases")]
    for case in cases.set_index("audit_id").loc[selected].reset_index().itertuples():
        note = (
            r" Selection: of the {n} audited cases with this outcome, the one with the "
            r"highest annotator confidence (lowest case number on ties)."
        ).format(n=counts[case.expert_outcome])
        parts.append(metric_case_figure(case, note))
    return parts


# Target audit (Appendix A.2)

def target_label(control_id):
    return "fig:target_audit_control_{}".format(control_id)


def target_case_figure(control, completions, note):
    experts = completions[completions["control_id"].eq(control.control_id)
                          & completions["solution_rank"].eq(1)].sort_values("expert_id")
    alternatives = completions[completions["control_id"].eq(control.control_id)
                               & completions["solution_rank"].gt(1)]
    matching = (completions[completions["control_id"].eq(control.control_id)]
                .groupby("expert_id")["equivalent_match"].any())
    stem = "target_audit_{:03d}".format(control.control_id)
    rows = [
        ("USPTO input", render(control.input_reaction, stem + "_input.png")),
        ("FlowER target", render(control.flower_target, stem + "_target.png",
                                 differences(control.flower_target, experts["completion"]))),
    ]
    for expert in experts.itertuples():
        number = expert.expert_id.replace("Expert ", "")
        label = r"Annotator {}\newline({})".format(
            number, "match" if matching[expert.expert_id] else "no match")
        rows.append((label, render(
            expert.completion, "{}_expert{}.png".format(stem, number),
            differences(expert.completion, [control.flower_target]), control.flower_target)))
    agreeing = int(control.experts_matching)
    caption = (
        r"Target audit, control {id} ({uid}). {agree} of the three independent chemistry-annotator "
        r"completions {verb} the benchmark target under the equivalence metric.{alt} "
        r"{shading}{note}"
    ).format(
        id=control.control_id, uid=r"\texttt{%s}" % tex(control.unique_identifier),
        agree=NUMBERS[agreeing].capitalize(), verb="matches" if agreeing == 1 else "match",
        alt=" The first completion of each annotator is shown." if len(alternatives) else "",
        shading=SHADING, note=note,
    )
    return figure(rows, caption, target_label(control.control_id))


def target_appendix(controls, completions):
    levels = controls.groupby("experts_matching")["control_id"].apply(sorted)
    shown = {k: ids[:1] for k, ids in levels.items() if k > 0}
    shown[0] = levels.get(0, [])
    rows = []
    for k in sorted(levels.index, reverse=True):
        figure_refs = ", ".join(r"\ref{%s}" % target_label(i) for i in shown[k])
        rows.append("%d of 3 & %d & %s" % (k, len(levels[k]), figure_refs))
    caption = (
        r"Number of the 53 target-audit controls by how many of the three independent "
        r"chemistry-annotator completions match the benchmark target under the equivalence metric, "
        r"and the figures that show examples."
    )
    matched = [target_label(shown[k][0]) for k in sorted(shown, reverse=True) if k > 0]
    unmatched = [target_label(i) for i in shown[0]]
    text = (
        r"This appendix shows reactions from the record-level audit of benchmark targets "
        r"(Appendix~\ref{{app:target_audit}}). Table~\ref{{tab:target_audit_agreement}} "
        r"groups the 53 controls by how many of the three independent chemistry-annotator completions "
        r"match the benchmark target under the equivalence metric. For each level with at "
        r"least one match, we show the control with the lowest ID ({matched}). Control IDs "
        r"follow the order of the curation app, in which the controls were embedded at "
        r"random, so this choice does not depend on the reaction. We show all {n} controls "
        r"without a match ({unmatched}). Each figure shows the USPTO input, the FlowER "
        r"target and the first completion of each annotator, drawn at the same scale. "
        r"Shading marks molecules that differ between the target and a completion."
    ).format(matched=refs(matched), unmatched=refs(unmatched),
             n=NUMBERS.get(len(unmatched), len(unmatched)))
    parts = [intro("Reactions from the audit of benchmark targets",
                   "app:target_audit_cases", text)]
    parts += [table(r"Matching annotators & Controls & Figures", rows, "lrl", caption,
                   "tab:target_audit_agreement")]
    for k in sorted(shown, reverse=True):
        for control_id in shown[k]:
            control = controls[controls["control_id"].eq(control_id)].iloc[0]
            if k > 0:
                note = (r" Selection: the control with the lowest ID among the {n} "
                        r"controls with this level of agreement.").format(n=len(levels[k]))
            else:
                note = r" All {n} controls without a match are shown.".format(n=len(levels[k]))
            parts.append(target_case_figure(control, completions, note))
    return parts


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--tex-figure-dir", default="figures_camera_ready/audits",
                        help="image folder as seen from the main .tex file")
    parser.add_argument("--copy-figures-to", type=Path,
                        help="also copy the rendered images to this folder")
    args = parser.parse_args()
    RDLogger.DisableLog("rdApp.*")
    FIGURES.mkdir(parents=True, exist_ok=True)

    cases = pd.read_csv(OUT / "metric_audit_cases.csv")
    cases["expert_confidence"] = cases["expert_confidence"].str.strip()
    counts = cases["expert_outcome"].value_counts().to_dict()
    candidates = cases[cases["expert_outcome"].isin(SHOWN_OUTCOMES)]
    order = candidates.assign(
        outcome_rank=candidates["expert_outcome"].map(SHOWN_OUTCOMES.index),
        confidence_rank=candidates["expert_confidence"].map(CONFIDENCE),
    ).sort_values(["outcome_rank", "confidence_rank", "audit_id"])
    selected = order.drop_duplicates("expert_outcome")["audit_id"].tolist()

    controls = pd.read_csv(OUT / "target_audit_controls.csv")
    completions = pd.read_csv(OUT / "target_audit_completions.csv")

    metric_parts = metric_appendix(cases, selected, counts)
    target_parts = target_appendix(controls, completions)
    every_case = [metric_case_figure(case, label_prefix="fig:metric_audit_all_")
                  for case in cases.itertuples()]
    preamble = (PREAMBLE.replace("WIDEST", str(max(widths)))
                .replace("FIGURE_DIR", args.tex_figure_dir.rstrip("/")))

    # Keep the figures inside their own section. \clearpage needs no package;
    # redefine \expertauditbarrier as \FloatBarrier (placeins) to avoid the page break.
    barrier = r"\expertauditbarrier" + "\n"
    manuscript = {
        "appendix_target_audit.tex": "\n".join([preamble] + target_parts + [barrier]),
        "appendix_metric_audit.tex": "\n".join([preamble] + metric_parts + [barrier]),
    }
    for name, text in manuscript.items():
        (OUT / name).write_text(text, encoding="utf-8")
    repository = [preamble]
    for i, figure_text in enumerate(every_case):
        repository.append(figure_text)
        if i % 3 == 2:
            repository.append(r"\clearpage" + "\n")
    (OUT / "expert_audits_all_cases.tex").write_text("\n".join(repository), encoding="utf-8")
    for old in ("appendix_expert_audits.tex", "expert_audits_gallery.tex"):  # superseded
        (OUT / old).unlink(missing_ok=True)

    print("Metric-audit figures: cases {}".format(selected))
    print("Target-audit figures: controls {}".format(
        re.findall(r"label\{fig:target_audit_control_(\d+)", manuscript["appendix_target_audit.tex"])))
    print("Wrote LaTeX and {} images to {}".format(len(list(FIGURES.glob("*.png"))), OUT))
    if args.copy_figures_to:
        used = sorted({name for text in manuscript.values()
                       for name in re.findall(r"\\expertauditdir/([^}]+)", text)})
        args.copy_figures_to.mkdir(parents=True, exist_ok=True)
        for name in used:
            shutil.copy2(FIGURES / name, args.copy_figures_to / name)
        print("Copied the {} manuscript images to {}".format(len(used), args.copy_figures_to))


if __name__ == "__main__":
    main()
